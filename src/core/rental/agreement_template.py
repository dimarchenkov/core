def _replace_once(source: str, old: str, new: str) -> str:
    """Build the shipped v2 from v1 without duplicating the legal clauses."""
    if source.count(old) != 1:
        raise RuntimeError("Rental agreement v2 source no longer matches v1.")
    return source.replace(old, new, 1)


def _replace_first_of_two(source: str, old: str, new: str) -> str:
    """Replace the issue copy of a field block that also exists for return."""
    if source.count(old) != 2:
        raise RuntimeError("Rental agreement v2 paired fields no longer match v1.")
    return source.replace(old, new, 1)


